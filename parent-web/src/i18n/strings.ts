export const STRINGS: Record<Lang, Dict> = {en, et, de, es};

/** Each language by its own name, so a grown-up can always find theirs. */
export const LANG_NAMES: Record<Lang, string> = {en: 'English', et: 'Eesti', de: 'Deutsch', es: 'Español'};

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars: Vars = {}): string {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key];
  return template.replace(/\{(\w+)\}/g, (hole, name: string) => (name in vars ? String(vars[name]) : hole));
}

/** The first of the browser's languages that we have (before a family has chosen one); English otherwise. */
export function detectLang(preferred: readonly string[]): Lang {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split('-')[0];
    const match = langValues.find(lang => lang === base);
    if (match) return match;
  }
  return 'en';
}
