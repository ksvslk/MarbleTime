#!/usr/bin/env python3
"""Record every line the TV speaks as an MP3 clip, and write the clip map the app plays from.

The lines come from the app itself (spokenLines in voiceLines.ts, via scripts/voice-lines.ts), so what is
recorded always matches what is shown. Nothing is synthesised on the TV.

  English, German, Spanish: Amazon Polly neural voices (AWS CLI; credentials from `aws login`).
  Estonian: TartuNLP Neurokõne (api.tartunlp.ai), a free research API. Ask TartuNLP before a commercial launch.

Only new or changed lines are recorded; clips that no line uses any more are deleted.

Usage: python3 scripts/make-voices.py   (needs the AWS CLI and ffmpeg)
Output: tv/packages/shared/src/assets/voice/<lang>/*.mp3 and tv/packages/shared/src/marble/voices.ts
"""
import hashlib
import html
import json
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHARED = ROOT / "tv/packages/shared"
OUT = SHARED / "src/assets/voice"
MAP = SHARED / "src/marble/voices.ts"

# Friendly, clear voices, a little slower than normal for young listeners.
POLLY = {"en": "Ruth", "de": "Vicki", "es": "Lucia"}
POLLY_RATE = "92%"
NEUROKONE = {"speaker": "mari", "speed": 0.95}
# Maths is shown with symbols ("7 + 5 = 12") but said with words.
MATHS = {"en": ("plus", "is"), "et": ("pluss", "on"), "de": ("plus", "ist"), "es": ("más", "es")}


def lines_by_lang() -> dict:
    tsx = SHARED / "node_modules/.bin/tsx"
    out = subprocess.run([str(tsx), str(ROOT / "scripts/voice-lines.ts")], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def spoken(lang: str, text: str) -> str:
    plus, equals = MATHS[lang]
    return text.replace(" + ", f" {plus} ").replace(" = ", f" {equals} ")


def clip_name(lang: str, text: str) -> str:
    voice = POLLY.get(lang, json.dumps(NEUROKONE, sort_keys=True))
    return hashlib.sha1(f"{lang}|{voice}|{POLLY_RATE}|{text}".encode()).hexdigest()[:12] + ".mp3"


def polly(lang: str, text: str, raw: pathlib.Path) -> None:
    body = html.escape(spoken(lang, text)).replace("…", '<break time="600ms"/>')
    ssml = f'<speak><prosody rate="{POLLY_RATE}">{body}</prosody></speak>'
    subprocess.run(
        ["aws", "polly", "synthesize-speech", "--engine", "neural", "--voice-id", POLLY[lang], "--output-format", "mp3",
         "--sample-rate", "24000", "--text-type", "ssml", "--text", ssml, str(raw)],
        check=True, capture_output=True)


def neurokone(text: str, raw: pathlib.Path) -> None:
    # curl, not urllib: it uses the system certificates (python.org builds ship without any).
    body = json.dumps({"text": spoken("et", text).replace("…", ","), **NEUROKONE})
    subprocess.run(["curl", "-sSf", "-m", "60", "-X", "POST", "https://api.tartunlp.ai/text-to-speech/v2",
                    "-H", "Content-Type: application/json", "-d", body, "-o", str(raw)], check=True)


def finish(raw: pathlib.Path, out: pathlib.Path) -> None:
    """Trim the silence at both ends, even out loudness across both voice services, mono MP3."""
    trim = "silenceremove=start_periods=1:start_threshold=-45dB"
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", str(raw),
         "-af", f"{trim},areverse,{trim},areverse,loudnorm=I=-16:TP=-1.5:LRA=11",
         "-ac", "1", "-ar", "24000", "-b:a", "48k", str(out)],
        check=True)


def main() -> None:
    lines = lines_by_lang()
    made = 0
    entries = {}
    for lang, texts in lines.items():
        folder = OUT / lang
        folder.mkdir(parents=True, exist_ok=True)
        entries[lang] = {}
        for text in texts:
            name = clip_name(lang, text)
            entries[lang][text] = name
            if (folder / name).exists():
                continue
            with tempfile.TemporaryDirectory() as tmp:
                raw = pathlib.Path(tmp) / ("raw.wav" if lang == "et" else "raw.mp3")
                try:
                    neurokone(text, raw) if lang == "et" else polly(lang, text, raw)
                except subprocess.CalledProcessError as error:
                    sys.exit(f"Polly failed ({error.stderr.decode().strip()}). If the credentials expired, run `aws login`.")
                finish(raw, folder / name)
            made += 1
            print(f"  {lang}  {text}")
        for old in folder.glob("*.mp3"):
            if old.name not in entries[lang].values():
                old.unlink()

    rows = ["// Generated by scripts/make-voices.py from spokenLines() in voiceLines.ts. Do not edit.",
            "// Text → recorded clip, per language.",
            "export const VOICES: Record<string, Record<string, number>> = {"]
    for lang, clips in entries.items():
        rows.append(f"  {lang}: {{")
        rows += [f"    {json.dumps(text, ensure_ascii=False)}: require('../assets/voice/{lang}/{name}')," for text, name in clips.items()]
        rows.append("  },")
    rows.append("};")
    MAP.write_text("\n".join(rows) + "\n")
    print(f"recorded {made} new clips; {sum(len(c) for c in entries.values())} in {MAP.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
